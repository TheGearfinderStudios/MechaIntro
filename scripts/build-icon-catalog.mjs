/**
 * scripts/build-icon-catalog.mjs
 *
 * Boils Font Awesome's icon-families.json (5 MB, every Pro variant listed) down to
 * the free icons and the one thing the app needs from each: the SVG path. The stage
 * draws icons as Path2D, so an export never waits on a webfont to load.
 *
 * Runs on postinstall; `npm run icons` rebuilds it by hand.
 *
 * @author Gearfinder Studios
 * @license GPL-3.0-or-later
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'node_modules/@fortawesome/fontawesome-free/metadata/icon-families.json');
// A module rather than .json: the page is loaded from file://, where fetch() is not
// available and a JSON module import depends on how the file's MIME type is guessed.
const target = join(root, 'src/generated/icons.js');

const families = JSON.parse(readFileSync(source, 'utf8'));
const icons = [];

for (const [name, meta] of Object.entries(families)) {
	const styles = {};

	for (const { family, style } of meta.familyStylesByLicense?.free || []) {
		const svg = meta.svgs?.[family]?.[style];

		// Free only ships the classic family; brands sit under it as their own style.
		if (family !== 'classic' || !svg) {
			continue;
		}

		const path = Array.isArray(svg.path) ? svg.path : [svg.path];
		styles[style] = [svg.width, svg.height, ...path];
	}

	if (!Object.keys(styles).length) {
		continue;
	}

	icons.push({
		n: name,
		l: meta.label,
		t: (meta.search?.terms || []).join(' '),
		s: styles
	});
}

icons.sort((a, b) => a.n.localeCompare(b.n));

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `// Generated by scripts/build-icon-catalog.mjs - do not edit.\nexport default ${JSON.stringify(icons)};\n`);

console.log(`icon catalog: ${icons.length} icons -> ${target}`);
